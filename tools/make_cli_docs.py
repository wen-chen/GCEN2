"""Write docs/cli.rst, the command-line reference, from the gcen2 commands.

    python tools/make_cli_docs.py           # write docs/cli.rst
    python tools/make_cli_docs.py --check   # exit 1 if it is out of date

Built from the command functions themselves (their docstrings and
``typer.Option`` declarations), not from typer's internals, so the text is
the same with every typer version (tests/test_cli_docs.py checks it)."""

from __future__ import annotations

import inspect
import re
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "docs" / "cli.rst"

_TYPES = [("bool", "flag"), ("int", "INTEGER"), ("float", "FLOAT"), ("str", "TEXT"),
          ("Path", "PATH")]


def _type(annotation) -> tuple[str, bool]:
    """Display type of an option and whether it can be repeated."""
    s = annotation if isinstance(annotation, str) else repr(annotation)
    s = re.sub(r"\btyping\.|\bpathlib\.|<class '|'>", "", s)
    repeat = bool(re.search(r"\b(list|List)\[", s))
    for name, shown in _TYPES:
        if re.search(rf"\b{name}\b", s):
            return shown, repeat
    return "VALUE", repeat


def _flags(name: str, info) -> str:
    decls = [d for d in (info.param_decls or ()) if d.startswith("-")]
    if not decls:
        decls = ["--" + name.replace("_", "-")]
    return ", ".join(f"``{d}``" for d in decls)


def _default(info) -> str:
    d = info.default
    if d is ... or d is None or d is False:
        return ""
    if d is True:
        return "on"
    if isinstance(d, float):
        return f"{d:g}"
    return str(d)


def _help(text: str) -> str:
    return " ".join((text or "").split()).replace("|", "\\|")


def _command_section(name: str, callback, prefix: str, skip=()) -> list[str]:
    from typer.models import OptionInfo

    doc = inspect.getdoc(callback) or ""
    title = f"{prefix} {name}"
    lines = [title, "-" * len(title), ""]
    if doc:
        lines += [" ".join(doc.split("\n\n")[0].split()), ""]
    rows = []
    for pname, p in inspect.signature(callback).parameters.items():
        info = p.default
        if not isinstance(info, OptionInfo) or getattr(info, "hidden", False) or \
                pname in skip:
            continue
        kind, repeat = _type(p.annotation)
        if kind == "flag":
            kind = ""
        required = info.default is ...
        note = "required" if required else _default(info)
        if repeat:
            note = (note + ", " if note else "") + "repeatable"
        rows.append((_flags(pname, info), kind, note, _help(info.help)))
    if rows:
        lines += [".. list-table::", "   :header-rows: 1", "   :widths: 26 10 14 50", "",
                  "   * - Option", "     - Type", "     - Default", "     - Description"]
        for flags, kind, note, hlp in rows:
            lines += [f"   * - {flags}"] + [f"     - {c}".rstrip() for c in (kind, note, hlp)]
        lines.append("")
    return lines


def render() -> str:
    from gcen2.cli import app, plot_app

    out = ["Command-line reference", "======================", "",
           ".. This file is generated by tools/make_cli_docs.py; do not edit it.", "",
           "Every command prints the same help with ``--help`` (e.g. "
           "``gcen2 build --help``). Options marked *repeatable* may be given several "
           "times; ``-t`` / ``--threads`` sets the number of threads.", "",
           "Analysis commands", "=================", ""]
    for info in app.registered_commands:
        name = info.name or info.callback.__name__.removeprefix("cmd_").replace("_", "-")
        out += _command_section(name, info.callback, "gcen2")
    out += ["Figures (``gcen2 plot``)", "========================", "",
            "Every ``gcen2 plot`` command also takes ``-o`` / ``--output`` (file stem, or "
            "one file by its extension), ``--size`` (``single`` 89 mm, ``onehalf`` 120 mm, "
            "``double`` 183 mm or a width in mm), ``--format`` (repeatable; default PDF, "
            "PNG and SVG) and ``--palette`` (``wgcna`` or ``okabe-ito``).", ""]
    for info in sorted(plot_app.registered_commands,
                       key=lambda i: i.name or i.callback.__name__):
        name = info.name or info.callback.__name__.removeprefix("plot_").replace("_", "-")
        out += _command_section(name, info.callback, "gcen2 plot",
                                skip=("output", "size", "formats", "palette"))
    return "\n".join(out).rstrip("\n") + "\n"


def main() -> int:
    text = render()
    if "--check" in sys.argv[1:]:
        if not OUT.is_file() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT} is out of date: run python tools/make_cli_docs.py")
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"{OUT}: {text.count(chr(10))} lines")
    return 0


if __name__ == "__main__":
    sys.exit(main())
